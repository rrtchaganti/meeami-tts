#!/usr/bin/env python
"""Evidence samples for the repository (DECISIONS E-36): `make samples` -> samples/.

    python scripts/export_samples.py [--config configs/samples.yaml]

Nothing is synthesized here. Every file is copied from where it was produced and checked by
sha256, so each sample is the exact audio behind a reported number or decision:

- samples/demo/<accent>/<id>/      held-out test set: reference.wav (L2-ARCTIC ground truth),
  text.txt, one wav per system (results/<system>/test/wav/<id>/out.wav), timings.json (reference
  words, each system's planned and MFA-measured words, per_utt.csv metrics), timing.png, README.md.
  Selection (configs/samples.yaml, fixed before listening): the headline prompt for every test
  speaker + the main system's best/median/worst utterance per accent.
- samples/listening/<set>/         the dev listening sets behind phase-2 decisions.
- samples/browser_tests/<job>/     the owner's browser-demo recordings (E-35) with outputs and
  alignments before and after the MFA-cache fix.
- samples/SOURCES.tsv + MANIFEST.sha256: provenance and hashes of every file.
"""
from __future__ import annotations

import argparse
import csv
import json
import shutil
import sys
from pathlib import Path

sys.path[0] = str(Path(__file__).resolve().parents[1])

from tts.config import REPO_ROOT, load_config, repo_path  # noqa: E402
from tts.splits import sha256  # noqa: E402

SILENCE = {"", "<eps>", "sil", "sp", "spn"}


class Exporter:
    def __init__(self, cfg, out: Path):
        self.cfg, self.s, self.out = cfg, cfg.samples, out
        self.sources: list[tuple[str, str]] = []

    # -- copying with provenance ------------------------------------------------------------
    def copy(self, src: Path, dst: Path) -> Path:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        if sha256(src) != sha256(dst):
            raise SystemExit(f"[samples] copy mismatch {src}")
        self.sources.append((self.rel(dst), _rel(src)))
        return dst

    def write(self, dst: Path, text: str, source: str = "generated by scripts/export_samples.py"):
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text)
        self.sources.append((self.rel(dst), source))

    def rel(self, p: Path) -> str:
        return str(p.relative_to(self.out))

    # -- held-out demonstration ---------------------------------------------------------------
    def select(self, per: dict[str, dict[str, dict]]) -> dict[str, list[tuple[str, str]]]:
        """accent -> [(id, why)]: headline prompt for every speaker + best/median/worst main MAE."""
        main = per[self.s.main]
        by_acc: dict[str, list[dict]] = {}
        for r in main.values():
            by_acc.setdefault(r["accent"], []).append(r)
        sel = {}
        for acc, rows in sorted(by_acc.items()):
            picks = [(r["id"], "headline prompt") for r in sorted(rows, key=lambda r: r["id"])
                     if r["id"].endswith(self.s.headline_prompt)]
            ok = sorted((r for r in rows if r["status"] == "ok" and r["wb_mae_ms"]),
                        key=lambda r: (float(r["wb_mae_ms"]), r["id"]))
            for why, q in self.s.quantiles.items():
                r = ok[round(q * (len(ok) - 1))]
                picks.append((r["id"], f"{why} main-system MAE ({float(r['wb_mae_ms']):.1f} ms)"))
            seen, uniq = set(), []
            for i, why in picks:
                if i not in seen:
                    seen.add(i)
                    uniq.append((i, why))
            sel[acc] = uniq
        return sel

    def demo(self) -> list[dict]:
        split = self.s.split
        per = {s: {r["id"]: r for r in csv.DictReader(open(repo_path("results") / s / split
                                                           / "per_utt.csv"))}
               for s in self.s.systems}
        rows = []
        for acc, picks in self.select(per).items():
            for uid, why in picks:
                rows.append(self.demo_one(acc, uid, why, per))
        return rows

    def demo_one(self, acc: str, uid: str, why: str, per) -> dict:
        split = self.s.split
        d = self.out / "demo" / acc / uid
        tm = {s: json.loads((repo_path("results") / s / split / "wav" / uid / "timings.json")
                            .read_text()) for s in self.s.systems}
        t0 = tm[self.s.main]
        ref_src = Path(t0["reference"])
        self.copy(ref_src, d / "reference.wav")
        # ground truth for the metric: L2-ARCTIC's manual word annotation (scripts/evaluate.py)
        spk, utt = uid.split("_", 1)
        l2 = load_config(REPO_ROOT / "configs" / "splits.yaml").l2   # dataset layout
        ann = repo_path(self.cfg.paths.raw_l2) / spk / l2.annotation_dir / f"{utt}.TextGrid"
        self.copy(ann, d / "reference_annotation.TextGrid")
        truth = annotation_words(ann)
        self.write(d / "text.txt", t0["text"] + "\n", _rel(ref_src.parent.parent / "transcript"
                                                          / f"{ref_src.stem}.txt"))
        systems = {}
        for s in self.s.systems:
            res = repo_path("results") / s / split
            self.copy(res / "wav" / uid / "out.wav", d / f"{s}.wav")
            measured = textgrid_words(res / "align_out" / f"{uid}.TextGrid")
            m = per[s][uid]
            check_mae(truth, measured, m["wb_mae_ms"], f"{s}/{uid}")
            systems[s] = {
                "label": self.s.labels[s],
                "planned_words": tm[s]["out_words"],
                "measured_words": measured,
                "per_word_error_ms": word_errors(truth, measured),
                "metrics": {k: _num(m[k]) for k in ("status", "aligner", "length_error",
                                                     "wb_mae_ms", "wer", "utmos", "us_prob")},
                "source": f"results/{s}/{split}/wav/{uid}/out.wav",
            }
        info = {"id": uid, "accent": acc, "why_selected": why, "text": t0["text"],
                "normalized": t0["normalized"], "reference": _rel(ref_src),
                "ref_duration_s": t0["ref_duration_s"], "annotation_words": truth,
                "ref_words": t0["ref_words"],
                "systems": systems}
        self.write(d / "timings.json", json.dumps(info, indent=1) + "\n")
        plot_sample(info, d / "reference.wav", {s: d / f"{s}.wav" for s in self.s.systems},
                    self.s.main, d / "timing.png", int(self.s.plot_dpi))
        self.sources.append((self.rel(d / "timing.png"), "generated by scripts/export_samples.py"))
        self.write(d / "README.md", sample_readme(info, self.s.main))
        return info

    # -- listening sets -----------------------------------------------------------------------
    def listening(self) -> list[dict]:
        out = []
        for name, ls in self.s.listening.items():
            src = repo_path(ls.src)
            dst = self.out / "listening" / name
            verified = 0
            for f in sorted(src.rglob("*")):
                if f.is_file():
                    self.copy(f, dst / f.relative_to(src))
            for folder in sorted(p for p in src.iterdir() if p.is_dir()):
                uid = "_".join(folder.name.split("_")[-3:])
                for wav, system in ls.outputs.items():
                    ev = repo_path("results") / system / "dev" / "wav" / uid / "out.wav"
                    if ev.exists() and sha256(ev) == sha256(folder / f"{wav}.wav"):
                        verified += 1
            n = sum(1 for p in src.iterdir() if p.is_dir())
            self.write(dst / "README.md", f"# Listening set `{name}`\n\n**Decision:** {ls.decision}"
                       f"\n\n**Claim:** {ls.claim}\n\nCopied unchanged from `{ls.src}/` (the files "
                       f"listened to). `0_reference.wav` is the L2-ARCTIC recording. {verified} "
                       f"output wavs were checked byte-identical to the dev evaluation outputs "
                       f"(`results/<system>/dev/wav/<id>/out.wav`), so the metrics in "
                       f"`results/<system>/dev/per_utt.csv` describe these exact files. "
                       f"`index.csv` lists the texts and per-utterance scores. {n} folders.\n")
            out.append({"name": name, "folders": n, "verified": verified, **dict(ls)})
        return out

    # -- browser tests (E-35) -----------------------------------------------------------------
    def browser_tests(self) -> list[dict]:
        b = self.s.browser_tests
        jobs: dict[str, Path] = {}
        for src in b.src:
            for d in sorted(repo_path(src).iterdir()):
                if (d / "result.json").exists() and d.name not in jobs:
                    jobs[d.name] = d
        order = sorted(jobs, key=lambda j: jobs[j].stat().st_mtime)
        fixed_at = jobs[b.first_job_after_fix].stat().st_mtime
        realigned = repo_path(b.realigned)
        rows = []
        for j in order:
            src, dst = jobs[j], self.out / "browser_tests" / j
            r = json.loads((src / "result.json").read_text())
            rec = next(p for p in (src / "upload.webm", src / f"ref{_ext(r)}") if p.exists())
            self.copy(rec, dst / f"recording{rec.suffix}")
            self.copy(src / "ref.TextGrid", dst / "reference_mfa.TextGrid")
            for s in b.systems:
                self.copy(src / s / "out.wav", dst / f"{s}.wav")
                if (src / "align_out" / f"{s}.TextGrid").exists():
                    self.copy(src / "align_out" / f"{s}.TextGrid", dst / f"{s}_measured.TextGrid")
            for suffix, name in (("", "reference_mfa_after_fix"), ("_ay", "reference_mfa_a_EY1")):
                p = realigned / f"{j}{suffix}.TextGrid"
                if p.exists():
                    self.copy(p, dst / f"{name}.TextGrid")
            keep = {k: r[k] for k in ("text", "normalized", "oov_added", "ref_duration_s",
                                      "ref_words", "align_s", "total_s") if k in r}
            keep["systems"] = [{k: v for k, v in s.items() if k not in ("plot", "label")}
                               for s in r["systems"] if s["name"] in b.systems]
            self.write(dst / "result.json", json.dumps(keep, indent=1) + "\n",
                       _rel(src / "result.json") + " (systems not committed removed)")
            tags = b.tags.get(j, [])
            tags = [tags] if isinstance(tags, str) else list(tags)
            main = next(s for s in r["systems"] if s["name"] == "main")
            rows.append({"job": j, "after_fix": jobs[j].stat().st_mtime >= fixed_at,
                         "text": r["text"], "normalized": r["normalized"],
                         "aligner": main["aligner"], "fallback": main.get("mfa_fallback_reason"),
                         "mae": main.get("measured_mae_ms"), "ref_words": r["ref_words"],
                         "tags": tags,
                         "after_fix_words": textgrid_words(realigned / f"{j}.TextGrid")
                         if (realigned / f"{j}.TextGrid").exists() else None})
        self.write(self.out / "browser_tests" / "README.md", browser_readme(rows, b))
        return rows

    def finish(self, demo, listening, browser):
        self.write(self.out / "README.md", top_readme(self.cfg, demo, listening, browser))
        self.sources.sort()
        self.write(self.out / "SOURCES.tsv", "file\tsource\n" + "".join(
            f"{a}\t{b}\n" for a, b in self.sources))
        files = sorted(p for p in self.out.rglob("*") if p.is_file() and p.name != "MANIFEST.sha256")
        (self.out / "MANIFEST.sha256").write_text("".join(
            f"{sha256(p)}  {self.rel(p)}\n" for p in files))


# -- helpers ------------------------------------------------------------------------------------
def _rel(p: Path) -> str:
    p = Path(p).resolve()
    try:
        return str(p.relative_to(REPO_ROOT))
    except ValueError:
        return str(p)


def _ext(r: dict) -> str:
    return Path(r.get("reference", "ref.wav")).suffix or ".wav"


def _num(v):
    try:
        return round(float(v), 4)
    except (TypeError, ValueError):
        return v


def textgrid_words(path: Path) -> list[dict]:
    from praatio import textgrid as tg

    g = tg.openTextgrid(str(path), includeEmptyIntervals=False)
    return [{"word": e.label, "start": round(e.start, 4), "end": round(e.end, 4)}
            for e in g.getTier("words").entries if e.label not in SILENCE]


def annotation_words(path: Path) -> list[dict]:
    """L2-ARCTIC manual word tier, read exactly as scripts/evaluate.py reads it."""
    from tts.align.l2 import manual_words
    from tts.align.textgrid import read_tiers

    return [{"word": w["word"], "start": round(w["start"], 4), "end": round(w["end"], 4)}
            for w in manual_words(read_tiers(path)[0])]


def word_errors(truth: list[dict], out: list[dict]) -> list[dict]:
    """Per annotated word: matched output word (same matching as the metric) and its start/end
    error in ms; unmatched words get None."""
    from tts.eval.metrics import match_words

    m = dict(match_words(truth, out))
    rows = []
    for i, a in enumerate(truth):
        b = out[m[i]] if i in m else None
        rows.append({"word": a["word"], "out": b,
                     "d_start_ms": round(1000 * (b["start"] - a["start"]), 1) if b else None,
                     "d_end_ms": round(1000 * (b["end"] - a["end"]), 1) if b else None})
    return rows


def check_mae(truth, out, reported, name):
    """Recompute the word-boundary MAE from the committed files; it must equal per_utt.csv."""
    from tts.eval.metrics import boundary_errors, boundary_summary

    got = boundary_summary(boundary_errors(truth, out))["mae_ms"]
    if reported not in ("", "nan") and abs(got - float(reported)) > 0.05:
        raise SystemExit(f"[samples] {name}: recomputed MAE {got:.2f} != per_utt {reported}")


def plot_sample(info: dict, ref_wav: Path, wavs: dict[str, Path], main: str, path: Path, dpi: int):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from tts.audio import load_wav
    from tts.infer.plot import _spec

    names = list(wavs)
    rows = [("reference: annotation", info["annotation_words"]),
            ("reference: MFA (copied)", info["ref_words"])] + [(info["systems"][s]["label"],
                                                  info["systems"][s]["measured_words"])
                                                 for s in names]
    fig, ax = plt.subplots(3, 1, figsize=(13, 7.5), sharex=True,
                           gridspec_kw={"height_ratios": [len(rows) * 0.45, 1.3, 1.3]})
    for i, (label, words) in enumerate(rows):
        y = len(rows) - 1 - i
        for w in words:
            ax[0].barh(y, w["end"] - w["start"], left=w["start"], height=0.8,
                       color="#4C72B0" if i < 2 else "#DD8452", edgecolor="white")
            ax[0].text(0.5 * (w["start"] + w["end"]), y, w["word"], ha="center", va="center",
                       fontsize=6, clip_on=True)
    ax[0].set_yticks(range(len(rows))[::-1], [r[0] for r in rows], fontsize=7)
    ax[0].set_title(f"{info['id']} ({info['accent']}): reference word timing vs each output, "
                    "measured by MFA on the output", fontsize=9)
    for a, (wav, name) in zip(ax[1:], [(ref_wav, "reference"), (wavs[main], main)]):
        y, sr = load_wav(wav)
        S, dur = _spec(y, sr)
        a.imshow(S, origin="lower", aspect="auto", extent=[0, dur, 0, S.shape[0]], cmap="magma")
        a.set_ylabel(name, fontsize=7)
    for a in ax:
        for w in info["annotation_words"]:
            a.axvline(w["start"], color="#4C72B0", lw=0.5, alpha=0.6)
            a.axvline(w["end"], color="#4C72B0", lw=0.5, alpha=0.6, ls="--")
    ax[-1].set_xlabel("time (s); blue lines = annotated (ground-truth) word boundaries")
    fig.tight_layout()
    fig.savefig(path, dpi=dpi)
    plt.close(fig)


def _f(v, fmt="{:.1f}"):
    return fmt.format(v) if isinstance(v, (int, float)) else str(v)


def sample_readme(info: dict, main: str) -> str:
    L = [f"# {info['id']} ({info['accent']}, held-out test speaker)", "",
         f"**Selected as:** {info['why_selected']}", "",
         f"**Text:** {info['text']}", "",
         f"**Reference (ground truth):** [`reference.wav`](reference.wav), L2-ARCTIC "
         f"`{Path(info['reference']).relative_to('data/raw/l2arctic') if info['reference'].startswith('data/raw/l2arctic') else info['reference']}`, "
         f"{info['ref_duration_s']:.2f} s; ground-truth word timing: "
         "[`reference_annotation.TextGrid`](reference_annotation.TextGrid) (L2-ARCTIC manual "
         "annotation, the reference for every MAE below)", "",
         "![timing](timing.png)", "",
         "| System | Output | Length error (samples) | Word-boundary MAE (ms, MFA on output) | WER | UTMOS | US prob |",
         "|---|---|---|---|---|---|---|"]
    for s, v in info["systems"].items():
        m = v["metrics"]
        L.append(f"| {v['label']} | [`{s}.wav`]({s}.wav) | {_f(m['length_error'], '{:.0f}')} | "
                 f"{_f(m['wb_mae_ms'])} | {_f(m['wer'], '{:.3f}')} | {_f(m['utmos'], '{:.2f}')} | "
                 f"{_f(m['us_prob'], '{:.2f}')} |")
    L += ["", f"**Word timings** (seconds). *Annotation* = human ground truth; *MFA on "
          f"reference* = the timing the system copies (input); *output* = MFA on the {main} "
          "output. Δ = output − annotation; the MAE above is the mean of |Δstart| and |Δend|, "
          "recomputed from these files and checked against `per_utt.csv`.", "",
          "| Word | Annotation | MFA on reference | Output | Δstart (ms) | Δend (ms) |",
          "|---|---|---|---|---|---|"]
    from tts.eval.metrics import match_words
    mfa = dict(match_words(info["annotation_words"], info["ref_words"]))
    for k, e in enumerate(info["systems"][main]["per_word_error_ms"]):
        a, o = info["annotation_words"][k], e["out"]
        r = info["ref_words"][mfa[k]] if k in mfa else None
        span = (lambda w: f"{w['start']:.2f}–{w['end']:.2f}" if w else "–")
        L.append(f"| {a['word']} | {span(a)} | {span(r)} | {span(o)} | "
                 f"{_f(e['d_start_ms']) if o else '–'} | {_f(e['d_end_ms']) if o else '–'} |")
    L += ["", "All systems' planned and measured word timings: [`timings.json`](timings.json). "
          "Each wav is a byte-exact copy of `results/<system>/test/wav/" + info["id"]
          + "/out.wav` (see `../../../SOURCES.tsv`).", ""]
    return "\n".join(L)


def browser_readme(rows: list[dict], b) -> str:
    L = ["# Browser-demo tests by the owner (2026-11-12, DECISIONS E-35)", "",
         "Every job the owner ran in the browser demo, in order, unfiltered. Each folder: the "
         "recording exactly as uploaded (`recording.webm`, playable in any browser), "
         "`reference_mfa.TextGrid` (MFA on the recording, as run), the main and V0 outputs with "
         "their measured TextGrids, and `result.json`. Where present: "
         "`reference_mfa_after_fix.TextGrid` (re-aligned after the cache fix) and "
         "`reference_mfa_a_EY1.TextGrid` (scratch lexicon with `a EY1`, diagnosis only).", "",
         "**Cases:**", ""]
    L += [f"- `{k}`: {v}" for k, v in b.cases.items()]
    L += ["", "Reference word durations come from MFA on the recording; ⚠ marks words under "
          "60 ms (collapsed). These recordings have no human annotation, so 'Output MAE' "
          "compares MFA on the main output with MFA on the recording (the timing the system "
          "copied): it measures timing transfer, not agreement with a ground truth, and is not "
          "comparable with the test-set MAE. Job order is chronological. One earlier job "
          "(\"Hi there, I'm chaganti\") was deleted by the demo's job limit before archiving; "
          "its recording was re-run after the fix as the job with that text below.", "",
          "| Job | Fix | Text | Normalized | Aligner | Reference words (s) | After fix (s) | Output MAE (ms) | Case |",
          "|---|---|---|---|---|---|---|---|---|"]

    def words(ws):
        return " ".join(f"{w['word']}({w['end'] - w['start']:.2f}{'⚠' if w['end'] - w['start'] < 0.06 else ''})"
                        for w in ws)
    for r in rows:
        al = r["aligner"] + (f" ({r['fallback']})" if r["fallback"] else "")
        L.append(f"| [`{r['job']}`]({r['job']}/) | {'after' if r['after_fix'] else 'before'} | "
                 f"{r['text']} | {r['normalized']} | {al} | {words(r['ref_words'])} | "
                 f"{words(r['after_fix_words']) if r['after_fix_words'] else ''} | "
                 f"{_f(r['mae'], '{:.0f}') if r['mae'] is not None else '–'} | "
                 f"{', '.join(r['tags'])} |")
    return "\n".join(L) + "\n"


def top_readme(cfg, demo, listening, browser) -> str:
    s = cfg.samples
    L = ["# Samples: the exact audio behind the reported results", "",
         "Built by `make samples` ([`scripts/export_samples.py`](../scripts/export_samples.py), "
         "[`configs/samples.yaml`](../configs/samples.yaml)). Nothing here was re-synthesized: "
         "each output is a byte-exact copy of the file the metrics were computed on "
         "([`SOURCES.tsv`](SOURCES.tsv) gives every file's origin, "
         "[`MANIFEST.sha256`](MANIFEST.sha256) its hash). References are unmodified "
         "L2-ARCTIC recordings (CC BY-NC 4.0).", "",
         "## 1. Demonstration on held-out accents (test split)", "",
         f"Selection, fixed in the config before listening: the headline prompt "
         f"`{s.headline_prompt}` for all 12 test speakers, plus the main system's best, median "
         "and worst utterance per accent by word-boundary MAE. So failures are shown, not only "
         "successes. Each folder has the input text, the reference, all 7 systems' outputs, "
         "word timings of the reference and every output (`timings.json`, `timing.png`) and a "
         "README with the per-utterance metrics from `results/<system>/test/per_utt.csv`.", "",
         "| Accent | Sample | Selected as | Text | Main MAE (ms) | V0 MAE (ms) |",
         "|---|---|---|---|---|---|"]
    for d in demo:
        L.append(f"| {d['accent']} | [`{d['id']}`](demo/{d['accent']}/{d['id']}/) | "
                 f"{d['why_selected']} | {d['text']} | "
                 f"{_f(d['systems'][s.main]['metrics']['wb_mae_ms'])} | "
                 f"{_f(d['systems']['v0']['metrics']['wb_mae_ms'])} |")
    o = cfg.hosting.outputs
    L += ["", "**All 1,248 test utterances × 7 systems** (the full evidence for every number in "
          "REPORT §11) are on the Hugging Face Hub: `make outputs` downloads, sha256-checks and "
          f"unpacks them into `results/<system>/{o.split}/` (`{cfg.hosting.hf_repo}`, "
          f"`outputs/{o.split}/<system>.tar`).", "",
          "## 2. Listening sets behind design decisions (dev split)", "",
          "| Set | Decision | Claim | Folders |", "|---|---|---|---|"]
    for ls in listening:
        L.append(f"| [`{ls['name']}`](listening/{ls['name']}/) | {ls['decision']} | "
                 f"{ls['claim']} | {ls['folders']} |")
    n_after = sum(r["after_fix"] for r in browser)
    L += ["", "## 3. Browser-demo tests and failure cases (E-35)", "",
          f"[`browser_tests/`](browser_tests/): all {len(browser)} jobs the owner ran on "
          f"2026-11-12 ({len(browser) - n_after} before and {n_after} after the MFA-cache fix), "
          "with the recordings. Open failures (letter `a`, `I` after a vowel) and fixed ones "
          "are tagged; see REPORT §15.", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default=str(REPO_ROOT / "configs" / "samples.yaml"))
    a = ap.parse_args()
    cfg = load_config(a.config)
    out = repo_path(cfg.samples.out_dir)
    if out.exists():
        shutil.rmtree(out)
    ex = Exporter(cfg, out)
    demo, listening, browser = ex.demo(), ex.listening(), ex.browser_tests()
    ex.finish(demo, listening, browser)
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    print(f"[samples] {len(demo)} demo samples, {len(listening)} listening sets, "
          f"{len(browser)} browser tests -> {_rel(out)} ({size / 1e6:.1f} MB)")
    return 0


